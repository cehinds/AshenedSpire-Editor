import {createRequire} from 'node:module';
import {mkdir, writeFile, readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {defaultBooks, exportBookRecipes} from '../src/book-art-model.mjs';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = new URL('../output/book-atelier/', import.meta.url);
await mkdir(root, {recursive:true});
const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME || undefined});
const page = await browser.newPage({viewport:{width:1600,height:1000}});
const errors = [], failed = [];
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => {if(response.status()>=400)failed.push(`${response.status()} ${response.url()}`);});
const url = process.env.BOOK_EDITOR_URL || 'http://127.0.0.1:8771/';
await page.goto(url);
await page.getByRole('button', {name:'Project tools',exact:true}).click();
const modes = page.getByRole('combobox', {name:'Canvas preview modes', exact:true});
if(await modes.count())await modes.selectOption('Book Atelier');
else await page.getByRole('tab',{name:'Book Atelier',exact:true}).click();
await page.getByRole('region',{name:'Book Atelier'}).waitFor();
await page.getByLabel('Leather color',{exact:true}).fill('#224466');
await page.getByRole('button',{name:'Use feat emblem',exact:true}).click();
assert.equal(await page.locator('.atelier-hero [data-book-symbol]').getAttribute('data-book-symbol'),'feat');
await page.getByRole('button',{name:'Use scholar binding',exact:true}).click();
assert.equal(await page.locator('.atelier-hero [data-book-cover]').getAttribute('data-book-cover'),'scholar');
const downloadWait = page.waitForEvent('download');
await page.getByRole('button',{name:'Export JSON',exact:true}).click();
const download = await downloadWait;
await download.saveAs(new URL('export.json',root).pathname.replace(/^\/(\w:)/,'$1'));
const exported = JSON.parse(await readFile(new URL('export.json',root),'utf8'));
assert.equal(exported.recipes.bladeManual.symbol,'feat');
assert.equal(exported.recipes.bladeManual.color,'#224466');
await page.locator('.book-atelier input[type=file]').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"bladeManual":{"color":"red"}}')});
await page.getByRole('alert').filter({hasText:'Unknown cover'}).waitFor();
assert.equal(await page.getByLabel('Leather color',{exact:true}).inputValue(),'#224466');
await page.locator('.book-atelier input[type=file]').setInputFiles({name:'good.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(exported))});
await page.waitForFunction(()=>!document.querySelector('.book-atelier [role=alert]'));
await page.screenshot({path:new URL('desktop.png',root).pathname.replace(/^\/(\w:)/,'$1'),fullPage:true});
await page.reload();
await page.getByRole('button', {name:'Project tools',exact:true}).click();
if(await modes.count())await modes.selectOption('Book Atelier');
else await page.getByRole('tab',{name:'Book Atelier',exact:true}).click();
assert.equal(await page.getByLabel('Leather color',{exact:true}).inputValue(),'#224466');
if (!process.env.BOOK_EDITOR_STATIC) {
  let content = exportBookRecipes(defaultBooks()), revision = 'revision-one', writes = 0;
  await page.route('**/api/workbench/**', async route => {
    const request=route.request(), path=new URL(request.url()).pathname;
    if(path.endsWith('/status'))return route.fulfill({json:{connected:true,csrfToken:'test-csrf',capabilities:['files']}});
    if(path.endsWith('/repos'))return route.fulfill({json:{repos:[{id:'book-test',name:'Book test checkout',kind:'local',status:'connected'}]}});
    if(path.endsWith('/file') && request.method()==='GET')return route.fulfill({json:{content,revision}});
    if(path.endsWith('/file') && request.method()==='PUT') {
      const body=request.postDataJSON();
      assert.equal(body.path,'src/content/bookArtPresets.js');
      assert.equal(request.headers()['x-workbench-csrf'],'test-csrf');
      if(body.revision!==revision)return route.fulfill({status:409,json:{error:'Checkout file changed since review.'}});
      content=body.content; revision='revision-saved'; writes++;
      return route.fulfill({json:{content,revision}});
    }
    return route.continue();
  });
  await page.getByText('Save artwork to game checkout',{exact:true}).click();
  await page.getByRole('button',{name:'Find local checkouts',exact:true}).click();
  await page.getByRole('button',{name:'Review artwork save',exact:true}).click();
  const save=page.getByRole('button',{name:'Save reviewed artwork to game',exact:true});
  await save.waitFor();
  await page.getByLabel('Leather color',{exact:true}).fill('#335577');
  assert.ok(await save.isDisabled(),'Changed draft invalidates review');
  await page.getByRole('button',{name:'Review artwork save',exact:true}).click();
  await page.waitForFunction(()=>!Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='Save reviewed artwork to game')?.disabled);
  revision='revision-external';
  await save.click();
  await page.getByRole('alert').filter({hasText:'Checkout file changed'}).waitFor();
  assert.equal(writes,0);
  await page.getByRole('button',{name:'Review artwork save',exact:true}).click();
  await page.getByLabel('Proposed book source',{exact:true}).waitFor();
  await save.click();
  await page.getByRole('status').filter({hasText:'Book artwork saved to the local checkout'}).waitFor();
  assert.equal(writes,1);
  assert.ok(content.includes('#335577'));
  await page.unroute('**/api/workbench/**');
}
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:new URL('mobile.png',root).pathname.replace(/^\/(\w:)/,'$1'),fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'No horizontal overflow');
assert.deepEqual(errors,[]);
assert.deepEqual(failed.filter(message=>!message.startsWith('409 ')),[]);
await writeFile(new URL('browser.json',root),JSON.stringify({url,errors,failed,checks:['book navigation','full binding color','feat emblem','cover variation','JSON export','invalid import atomicity','valid import','reload persistence','390px width']},null,2));
await browser.close();
console.log('Book Atelier browser checks passed.');
